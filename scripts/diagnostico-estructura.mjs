import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
const root=process.cwd();
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const fail=[];
const schema=read('prisma/schema.prisma');
const sql=read('prisma/migrations/20261121000100_initial/migration.sql');
const models=[...schema.matchAll(/^model\s+([A-Za-z][A-Za-z0-9]*)\s*\{/gm)].map(x=>x[1]);
const tables=[...sql.matchAll(/CREATE TABLE\s+"([A-Za-z][A-Za-z0-9]*)"/g)].map(x=>x[1]);
for(const model of models)if(!tables.includes(model))fail.push(`No existe CREATE TABLE de ${model}`);
for(const table of tables)if(!models.includes(table))fail.push(`Tabla sin modelo Prisma: ${table}`);
if(/\bDROP\s+(?:TABLE|SCHEMA)\b/i.test(sql))fail.push('La migración inicial contiene DROP');
for(const file of ['package.json','app/layout.tsx','app/login/page.tsx','app/dashboard/page.tsx','lib/prisma.ts','prisma/seed.ts','.github/workflows/validacion.yml'])if(!fs.existsSync(path.join(root,file)))fail.push(`Falta ${file}`);
const lock=fs.existsSync(path.join(root,'package-lock.json'));
const nodeMajor=Number(process.versions.node.split('.')[0]);
if(nodeMajor<22)fail.push('Node.js 22+ requerido');
const summary={status:fail.length?'ERROR':'OK',node:process.version,models:models.length,tablesInInitialMigration:tables.length,lockfile:lock?'presente':'pendiente de generar con npm install en TI',errores:fail};
console.log(JSON.stringify(summary,null,2));
if(fail.length)process.exitCode=1;
